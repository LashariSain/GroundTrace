"""
Report generator. Turns a Finding into a Markdown advisory that fills your five
fields plus the provenance (discovery + disclosure) layer and a timeline.

Kept as plain string building (no Jinja dependency) so it runs anywhere.
"""
from __future__ import annotations

from .models import Finding


def _sev_badge(f: Finding) -> str:
    s = f.scores
    parts = []
    if s.cvss is not None:
        parts.append(f"CVSS {s.cvss} ({s.cvss_severity or '?'})")
    if s.epss is not None:
        parts.append(f"EPSS {s.epss:.0%}")
    if s.risk is not None:
        parts.append(f"Risk {s.risk}")
    if f.disclosure.in_kev:
        parts.append("**KEV: actively exploited**")
    return " · ".join(parts) if parts else "unscored"


def _timeline(f: Finding) -> str:
    d = f.disclosure
    rows = []
    if f.published:
        rows.append(f"- **Published:** {f.published}")
    if d.disclosure_date:
        rows.append(f"- **Public disclosure:** {d.disclosure_date} "
                    f"({d.channel or 'unknown channel'})")
    if d.patch_date:
        rows.append(f"- **Patch released:** {d.patch_date}")
    if d.leaked_before_fix is True:
        rows.append("- ⚠️ **Weaponized/leaked BEFORE a fix existed** — treat as "
                    "effective zero-day; prioritize compensating controls.")
    elif d.leaked_before_fix is False:
        rows.append("- ✅ Patch was available at disclosure.")
    return "\n".join(rows) if rows else "_No timeline data._"


_MAX_AFFECTED_SHOWN = 25


def _affected_block(f: Finding) -> str:
    if not f.affected:
        return "_not specified_"
    shown = f.affected[:_MAX_AFFECTED_SHOWN]
    lines = [f"- `{x}`" for x in shown]
    remaining = len(f.affected) - len(shown)
    if remaining > 0:
        lines.append(f"- _...and {remaining} more (see JSON output with `--json` "
                     f"for the full list — {len(f.affected)} total)._")
    return "\n".join(lines)


def render_markdown(f: Finding) -> str:
    disc, disc2 = f.discovery, f.disclosure
    a = f.analysis
    aff = _affected_block(f)
    cwes = ", ".join(f.cwe_ids) or "unclassified"
    refs = "\n".join(f"- {u}" for u in f.references[:12]) or "_none_"

    def _ev(items: list[str]) -> str:
        return f" _(evidence: {'; '.join(items)})_" if items else ""

    return f"""# {f.cve_id} — {f.title or 'Vulnerability Advisory'}

> {_sev_badge(f)}
> Weakness: {cwes} | Affected: {len(f.affected)} target(s)

## 1. What the vulnerability is
{a.what_it_is or f.description or '_n/a_'}

## 2. Root cause (the underlying developer mistake)
{a.root_cause or '_Requires manual/LLM analysis of the affected code._'}

## 3. How it was found & how it became public
**Discovery method:** `{disc.method.value}` (confidence: {disc.confidence.value}){_ev(disc.evidence)}
{f"- Found by: {disc.found_by}" if disc.found_by else ""}
{f"- Detection signal: {disc.detection_signal}" if disc.detection_signal else ""}

**Disclosure basis:** `{disc2.basis.value}` (confidence: {disc2.confidence.value}){_ev(disc2.evidence)}
{f"- Channel: {disc2.channel}" if disc2.channel else ""}
- Public exploit available: {"yes" if disc2.exploit_public else "no"}
- On CISA KEV: {"yes" if disc2.in_kev else "no"}

### Timeline
{_timeline(f)}

## 4. Business impact
{a.business_impact or '_Set per asset criticality and data exposure._'}

## 5. Security design principle violated
{a.principle_violated or '_derived from CWE_'}

## Affected components
{aff}

## Remediation (recommend — human approves before applying)
- Fixed version: {f.remediation.fixed_version or 'see references'}
- Upgrade path: {f.remediation.upgrade_path or 'n/a'}
- Workaround: {f.remediation.workaround or 'n/a'}
- Action mode: `{f.remediation.action}`

## References
{refs}

---
*Generated by groundtrace. Provenance labels are heuristic — verify before publishing.*
"""
